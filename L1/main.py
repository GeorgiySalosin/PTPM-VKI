import math


def solve(s1: str, s2: str, s3: str):
    """
    Определяет вид треугольника по трём сторонам и вычисляет координаты его вершин.
    
    :param s1: строка с длиной стороны A
    :param s2: строка с длиной стороны B
    :param s3: строка с длиной стороны C
    :return: (тип_треугольника, [(x1,y1), (x2,y2), (x3,y3)])
    """
    # --- 1. Проверка на нечисловые данные ---
    try:
        a = float(s1)
        b = float(s2)
        c = float(s3)
    except (ValueError, TypeError):
        # Нечисловые данные -> пустая строка и координаты (-2, -2)
        return "", [(-2, -2), (-2, -2), (-2, -2)]

    # --- 2. Проверка на положительность и конечность ---
    # (NaN и inf тоже отсекаются через проверку isfinite и > 0)
    if not (math.isfinite(a) and math.isfinite(b) and math.isfinite(c)):
        return "не треугольник", [(-1, -1), (-1, -1), (-1, -1)]
    if a <= 0 or b <= 0 or c <= 0:
        return "не треугольник", [(-1, -1), (-1, -1), (-1, -1)]

    # --- 3. Проверка неравенства треугольника ---
    # Используем небольшую погрешность для float-сравнений
    eps = 1e-9
    if (a + b <= c + eps) or (a + c <= b + eps) or (b + c <= a + eps):
        return "не треугольник", [(-1, -1), (-1, -1), (-1, -1)]

    # --- 4. Определение типа треугольника ---
    if abs(a - b) < eps and abs(b - c) < eps:
        tri_type = "равносторонний"
    elif abs(a - b) < eps or abs(b - c) < eps or abs(a - c) < eps:
        tri_type = "равнобедренный"
    else:
        tri_type = "разносторонний"

    # --- 5. Вычисление координат вершин ---
    # Поле 100x100. Отступ (margin), чтобы треугольник не прилипал к краям.
    margin = 10
    field_size = 100
    available = field_size - 2 * margin  # 80 px

    # Находим наибольшую сторону, чтобы отмасштабировать треугольник
    max_side = max(a, b, c)

    # Масштаб: максимальная сторона занимает available пикселей
    scale = available / max_side if max_side > 0 else 1.0

    sa, sb, sc = a * scale, b * scale, c * scale

    # Размещаем сторону A горизонтально.
    # Вершина 1 (левый конец стороны A) — в левом нижнем углу области.
    # Вершина 2 (правый конец стороны A) — сдвинута вправо на sa.
    x1, y1 = float(margin), float(field_size - margin)
    x2, y2 = x1 + sa, y1

    # Вершина 3 (противолежащая стороне A) — находим через пересечение окружностей.
    # Расстояние от V1 до V3 = b, от V2 до V3 = c.
    # Координаты:
    #   x3 = (b^2 + a^2 - c^2) / (2a)  (в системе, где V1 в начале, V2 на оси X)
    #   y3 = sqrt(b^2 - x3^2)
    a_px, b_px, c_px = sa, sb, sc
    x3_local = (b_px ** 2 + a_px ** 2 - c_px ** 2) / (2 * a_px)
    y3_local_sq = b_px ** 2 - x3_local ** 2
    y3_local = math.sqrt(max(0.0, y3_local_sq))

    # Смещаем в координаты поля (ось Y направлена вниз, поэтому вычитаем)
    x3 = x1 + x3_local
    y3 = y1 - y3_local

    # Округляем до int (для отрисовки)
    coords = [
        (int(round(x1)), int(round(y1))),
        (int(round(x2)), int(round(y2))),
        (int(round(x3)), int(round(y3))),
    ]

    return tri_type, coords


# --- Примеры использования ---
if __name__ == "__main__":
    tests = [
        ("3", "3", "3"),      # равносторонний
        ("3", "3", "4"),      # равнобедренный
        ("3", "4", "5"),      # разносторонний
        ("1", "2", "10"),     # не треугольник
        ("-1", "2", "3"),     # не треугольник (отрицательная)
        ("abc", "2", "3"),    # нечисловые данные
        ("1.5", "2.5", "3.0"),
    ]

    for s1, s2, s3 in tests:
        t, coords = solve(s1, s2, s3)
        print(f"Стороны: ({s1}, {s2}, {s3}) -> Тип: '{t}', Координаты: {coords}")